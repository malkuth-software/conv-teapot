"""Turns data/teapot_bezier.txt (the original Newell/Blinn Bezier teapot from
the Utah Model Repository) into src/teapot_patches.inc: 28 patches of 16
control points, in file order."""
import re, sys
text = open(sys.argv[1]).read()
points = re.findall(r'pt\(\s*([-\d.eE]+)\s*,\s*([-\d.eE]+)\s*,\s*([-\d.eE]+)\s*\)', text)
assert len(points) == 28 * 16
with open(sys.argv[2], "w") as out:
    out.write("// Generated by tools/make_patch_header.py from data/teapot_bezier.txt.\n")
    out.write("// The Utah Teapot: original Bezier data of Martin Newell, scaled by Jim Blinn.\n")
    for k in range(28):
        out.write("{")
        out.write(", ".join("{%s, %s, %s}" % p for p in points[16 * k:16 * k + 16]))
        out.write("},\n")
