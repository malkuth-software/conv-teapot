"""Turns data/utah_teapot_samples.json into src/utah_samples.inc.

The JSON holds points ON the surface of two versions of the Utah Teapot, as
produced by the mesh generator of the official page
(https://graphics.cs.utah.edu/teapot/) at 8 intervals per patch, without
trimming or chamfers: the 2026 version (Cem Yuksel) and the round bottom of
the 1987 version (Frank Crow). Symmetric copies are stored once.
The points are converted here from z-up to this project's y-up frame."""
import base64, json, struct, sys

payload = json.load(open(sys.argv[1]))
res = payload["res"]
n = res + 1

def floats(b64):
    raw = base64.b64decode(b64)
    return struct.unpack("<%df" % (len(raw) // 4), raw)

def expand(unique, instances):
    """All patches as lists of (x, y, z) in this project's frame, row-major."""
    out = []
    for u, op, perm in instances:
        src = unique[u]
        turns, mirror = op % 4, op >= 4
        t, fi, fj = perm >> 2, (perm >> 1) & 1, perm & 1
        patch = []
        for j in range(n):
            for i in range(n):
                i2 = res - i if fi else i
                j2 = res - j if fj else j
                if t: i2, j2 = j2, i2
                x, y, z = src[j2 * n + i2]
                if mirror: y = -y
                for _ in range(turns): x, y = -y, x
                patch.append((x, z, -y))   # z-up -> y-up, a proper rotation
        out.append(patch)
    return out

def unique_patches(data):
    f = floats(data)
    count = len(f) // (3 * n * n)
    return [[tuple(f[3 * (k * n * n + p) + c] for c in range(3)) for p in range(n * n)] for k in range(count)]

v = payload["v2026"]
u26 = unique_patches(v["data"])
patches = expand(u26, v["instances"])
tags = [v["tags"][inst[0]] for inst in v["instances"]]
bottom = expand(unique_patches(payload["v1987_bottom"]["data"]), payload["v1987_bottom"]["instances"])

with open(sys.argv[2], "w") as out:
    out.write("// Generated by tools/make_utah_header.py from data/utah_teapot_samples.json.\n")
    out.write("// Points on the surface of the Utah Teapot, 9 by 9 per patch, y up.\n")
    out.write("// 2026 version (Cem Yuksel), without trimming or chamfers; round bottom of the 1987 version (Frank Crow).\n")
    out.write("static constexpr int utah_res = %d;\n" % res)
    out.write("static constexpr int utah2026_count = %d;\n" % len(patches))
    out.write("static const char* const utah2026_tags[%d] = {%s};\n" % (len(tags), ", ".join('"%s"' % t for t in tags)))
    def table(name, ps):
        out.write("static const float %s[%d][%d][3] = {\n" % (name, len(ps), n * n))
        for p in ps:
            out.write("{" + ",".join("{%.9g,%.9g,%.9g}" % q for q in p) + "},\n")
        out.write("};\n")
    table("utah2026_points", patches)
    out.write("static constexpr int utah1987_bottom_count = %d;\n" % len(bottom))
    out.write("static constexpr float utah1987_lift = %.9gf;\n" % payload["v1987_bottom"]["lift"])
    table("utah1987_bottom_points", bottom)
print(len(patches), "patches;", {t: tags.count(t) for t in sorted(set(tags))}, "; bottom", len(bottom))
