"""Turns data/utah_teapot_dense.json into src/utah_dense.inc.

Denser points on the 2026 Utah Teapot, from the mesh generator of the
official page: the meridian curves of the body and of the lid (49 points per
source patch edge), and one mirror half of the handle and spout surfaces
(17 by 17 points per patch). Converted from z-up to this project's y-up frame:
profiles become (radius, height); tube points become (x, z, -y)."""
import base64, json, struct, sys
p = json.load(open(sys.argv[1]))
def floats(b64):
    raw = base64.b64decode(b64)
    return struct.unpack("<%df" % (len(raw) // 4), raw)
with open(sys.argv[2], "w") as out:
    out.write("// Generated by tools/make_dense_header.py from data/utah_teapot_dense.json.\n")
    n = p["profile_res"] + 1
    out.write("static constexpr int dense_profile_points = %d;\n" % n)
    for name in ("body", "lid"):
        f = floats(p[name]["data"]); count = p[name]["count"]
        out.write("static constexpr int dense_%s_runs = %d;\n" % (name, count))
        out.write("static const float dense_%s_profile[%d][%d][2] = {\n" % (name, count, n))
        for r in range(count):
            out.write("{" + ",".join("{%.9g,%.9g}" % (abs(f[2 * (r * n + k)]), f[2 * (r * n + k) + 1]) for k in range(n)) + "},\n")
        out.write("};\n")
    m = p["tube_res"] + 1
    out.write("static constexpr int dense_tube_points = %d;\n" % m)
    for name in ("handle", "spout"):
        f = floats(p[name]["data"]); count = p[name]["count"]
        out.write("static constexpr int dense_%s_patches = %d;\n" % (name, count))
        out.write("static const float dense_%s_points[%d][%d][3] = {\n" % (name, count, m * m))
        for q in range(count):
            pts = []
            for k in range(m * m):
                x, y, z = f[3 * (q * m * m + k):3 * (q * m * m + k) + 3]
                pts.append("{%.9g,%.9g,%.9g}" % (x, z, -y))
            out.write("{" + ",".join(pts) + "},\n")
        out.write("};\n")
print("ok")
